import streamlit as st
from analyzer import get_stock_data, calculate_indicators, get_signal

st.set_page_config(
    page_title="Global Stock Analyzer",
    page_icon="📈",
    layout="wide"
)

st.title("📈 Global Stock Analyzer")
st.write("Analyze stocks using historical market data.")

ticker = st.text_input(
    "Enter stock symbol",
    placeholder="Example: AAPL"
)

if st.button("Analyze Stock"):
    if ticker:
        with st.spinner("Analyzing..."):

            data = get_stock_data(ticker.upper())

            if data is None:
                st.error("Stock not found or no data available.")
            else:
                data = calculate_indicators(data)
                signal = get_signal(data)

                latest = data.iloc[-1]

                st.subheader(f"{ticker.upper()} Analysis")

                col1, col2, col3 = st.columns(3)

                col1.metric(
                    "Current Price",
                    f"{latest['Close']:.2f}"
                )

                col2.metric(
                    "RSI",
                    f"{latest['RSI']:.2f}"
                )

                col3.metric(
                    "Signal",
                    signal
                )

                st.subheader("Price History")

                st.line_chart(data["Close"])

                st.subheader("Moving Averages")

                chart_data = data[
                    ["Close", "SMA_20", "SMA_50"]
                ].dropna()

                st.line_chart(chart_data)

                st.subheader("Analysis")

                if signal == "BUY":
                    st.success("🟢 BUY signal generated by the model.")
                elif signal == "SELL":
                    st.error("🔴 SELL signal generated by the model.")
                else:
                    st.warning("🟡 HOLD signal generated by the model.")

                st.caption(
                    "This is a model-generated signal for research purposes, "
                    "not a guarantee of future returns."
                )
    else:
        st.warning("Please enter a stock symbol.")
